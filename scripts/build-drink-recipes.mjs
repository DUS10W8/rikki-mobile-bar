// Writes supabase/migrations/20261120000000_drink_builder.sql from src/order/drinkBuilder.json.
// Run again after changing the builder's liquors, styles or option recipes, then apply the SQL.
import { readFile, writeFile } from "node:fs/promises";
import { componentRecipes } from "../src/order/drinkBuilder.js";

const config = JSON.parse(await readFile(new URL("../src/order/drinkBuilder.json", import.meta.url), "utf8"));
const rows = componentRecipes(config);
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sql = `-- Register drink builder (Abe's iPad). Generated by scripts/build-drink-recipes.mjs; do not edit by hand.
-- 1. walkup_checkouts.display_lines: what the guest and the register show (one line per drink, with options).
--    items keeps the inventory components (pour, style, options) that record_order_lines deducts.
-- 2. Recipes for every builder component: 1.5 fl oz per pour, another 1.5 for a double, mixers,
--    a cup per drink, 5 oz ice for iced drinks, and the extras the options add.
-- Safe to re-run.

alter table public.walkup_checkouts add column if not exists display_lines jsonb;

insert into public.recipe_lines (menu_item_id, sku, quantity) values
${rows.map(([id, sku, amount]) => `  (${quote(id)}, ${quote(sku)}, ${amount})`).join(",\n")}
on conflict (menu_item_id, sku) do update set quantity = excluded.quantity;
`;
await writeFile(new URL("../supabase/migrations/20261120000000_drink_builder.sql", import.meta.url), sql);
console.log(`Wrote ${rows.length} recipe lines.`);
